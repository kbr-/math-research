"""Do generic forms split over the weak base plus a closed column member (conj:closed-base-splitting)?

Weak unary PHP top algebra A over F_3, n holes, n + 1 rows, through degree 3 (a4lib normal forms, as in the recorded
splitting checks).  Closed member of an allowed set Z (in the slice sum c = n + 1 mod 3): by lem:closure-saturation its
top ideal N is spanned in degree t by x_Y * tau(C), Y a column-injective cell set in rows 1..n, tau in a_{S(Y), t-|Y|},
where a_{S,e} = degree-e parts of polynomials of degree <= e in the C_j (j not in S) vanishing on Z_S.  A# = A/N.
Tested statement: HS(A#/(l_1..l_k)A#) = HS(A#)/(1+q+q^2)^k through degree 3 for uniform random forms l (row-dependent
generic forms), i.e. A# is free over F[l]/(l^3) through degree 3.  Controls: 'unclosed' is the ideal of A generated by
the augmented member's tops a_{empty,e} (A-monomials times them); the whole slice gives the base.  Reported: the closure's effect dim N_t - dim N^unclosed_t in A.
Usage: python3 closed_split.py --n 8 --member base|selector|clause2|merge --seed S --k 4 --out OUT.json"""
import itertools, json, os, sys, time
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); RES = os.path.join(HERE, '..')
sys.path.insert(0, os.path.join(RES, 'odd_prime_degree_four_20260923')); import a4lib as L
sys.path.insert(0, os.path.join(RES, 'odd_prime_permutation_forms_20260923')); from gf3_prefix import prefix_ranks
a = dict(zip(sys.argv[1::2], sys.argv[2::2])); n = int(a['--n']); member = a['--member']; sd = int(a['--seed'])
kr = int(a['--k']); outp = a['--out']; K = 3; p = 3; P1 = n + 1; m = P1
t0 = time.time(); L.setup(n); Q = {}; g = {0: 1}
for k in range(1, K + 1): Q[k], g[k] = L.quotient(k, 2)
basis = {k: [q['cols'][c] for q in Q[k].values() for c in q['nonp']] for k in Q}; basis[0] = [()]
rnd = np.random.default_rng(1000 + sd)
phi = []
while len(phi) < 2:
    f = rnd.integers(1, p, size=n)
    if len(set(f.tolist())) > 1: phi.append(f)
v = rnd.integers(0, p, size=2)
ell = lambda b, c: int(sum(int(x) * y for x, y in zip(phi[b], c)) % p)
slice_ = [c for c in itertools.product((0, 1), repeat=n) if sum(c) % p == m % p]
allowed = {'base': lambda c: True, 'selector': lambda c: ell(0, c) != v[0],
           'clause2': lambda c: (ell(0, c), ell(1, c)) != (int(v[0]), int(v[1])), 'merge': lambda c: not (c[0] and c[1])}[member]
Z = [c for c in slice_ if allowed(c)]; assert Z

def rank3(M):
    M = M.copy() % 3; r = 0
    for c in range(M.shape[1]):
        piv = next((i for i in range(r, M.shape[0]) if M[i, c]), None)
        if piv is None: continue
        M[[r, piv]] = M[[piv, r]]; M[r] = (M[r] * (1 if M[r, c] == 1 else 2)) % 3
        nz = np.nonzero(M[:, c])[0]; nz = nz[nz != r]; M[nz] = (M[nz] - np.outer(M[nz, c], M[r])) % 3; r += 1
        if r == M.shape[0]: break
    return M[:r]
def kernel3(M):  # left kernel rows of M (rows x cols)
    A_ = np.concatenate([M % 3, np.eye(M.shape[0], dtype=np.int64)], axis=1); r = 0
    for c in range(M.shape[1]):
        piv = next((i for i in range(r, A_.shape[0]) if A_[i, c]), None)
        if piv is None: continue
        A_[[r, piv]] = A_[[piv, r]]; A_[r] = (A_[r] * (1 if A_[r, c] == 1 else 2)) % 3
        nz = np.nonzero(A_[:, c])[0]; nz = nz[nz != r]; A_[nz] = (A_[nz] - np.outer(A_[nz, c], A_[r])) % 3; r += 1
    return A_[r:, M.shape[1]:]
tops = {}   # (S, e) -> (list of degree-e monomials in C over holes outside S, basis rows of a_{S,e})
for s in range(0, K + 1):
    for S in itertools.combinations(range(n), s):
        rest = [j for j in range(n) if j not in S]; ZS = [c for c in Z if all(c[j] for j in S)]
        for e in range(0, K - s + 1):
            mons = [T for d in range(e + 1) for T in itertools.combinations(rest, d)]
            top = [T for T in mons if len(T) == e]
            if not ZS: tops[(S, e)] = (top, np.eye(len(top), dtype=np.int64)); continue
            ev = np.array([[int(all(c[j] for j in T)) for c in ZS] for T in mons], dtype=np.int64)
            ker = kernel3(ev); idx = [mons.index(T) for T in top]
            tops[(S, e)] = (top, rank3(ker[:, idx]) if len(ker) else np.zeros((0, len(top)), dtype=np.int64))
print('tops ready', f'({time.time()-t0:.0f}s)', flush=True)
def C_poly(T):  # product of C_j = sum_i x_ij over j in T, as an a4lib polynomial
    out = {(): 1}
    for j in T: out = L.mul(out, {(i * n + j,): 1 for i in range(P1)})
    return out
def rows_N(t, closed):
    rows = []
    if not closed:   # ideal generated in A by the augmented member's tops: monomials of A times a_{empty,e}, e <= t
        for e in range(1, t + 1):
            top, B = tops[((), e)]
            for b in B:
                tau = {}
                for coef, T in zip(b, top):
                    if coef % 3:
                        for mm, cc in C_poly(T).items(): tau[mm] = (tau.get(mm, 0) + coef * cc) % 3
                for mm in basis[t - e]:
                    poly = L.mul({mm: 1}, tau) if mm else tau
                    if poly: rows.append(L.normal_form(poly, Q[t], g[t]) % 3)
        return np.array(rows, dtype=np.uint8).reshape(-1, g[t])
    for s in range(0, t + 1):
        e = t - s
        for S in itertools.combinations(range(n), s):
            top, B = tops[(S, e)]
            if not len(B): continue
            Cp = {T: C_poly(T) for T in top}
            for Yrows in itertools.product(range(1, P1), repeat=s):
                xY = {tuple(sorted(i * n + j for i, j in zip(Yrows, S))): 1}
                for b in B:
                    poly = {}
                    for coef, T in zip(b, top):
                        if coef % 3:
                            for mm, cc in L.mul(xY, Cp[T]).items(): poly[mm] = (poly.get(mm, 0) + coef * cc) % 3
                    if poly: rows.append(L.normal_form(poly, Q[t], g[t]) % 3)
    return np.array(rows, dtype=np.uint8).reshape(-1, g[t])
rand = [rnd.integers(0, 3, size=(P1, n)) for _ in range(kr)]
def form_rows(F, t):
    lin = {(i * n + j,): int(F[i, j]) for i in range(P1) for j in range(n) if F[i, j] % 3}
    R_ = np.zeros((len(basis[t - 1]), g[t]), dtype=np.uint8)
    for r_, mm in enumerate(basis[t - 1]): R_[r_] = L.normal_form(L.mul({mm: 1}, lin) if mm else lin, Q[t], g[t]) % 3
    return R_
def series(closed):
    H = {}
    for t in range(1, K + 1):
        blocks = [rows_N(t, closed)] + [form_rows(F, t) for F in rand]
        blocks = [b if b.shape[0] else np.zeros((0, g[t]), dtype=np.uint8) for b in blocks]
        P_, W_ = L.gf3.pack(np.vstack(blocks))[:2]
        rk = prefix_ranks(np.ascontiguousarray(P_, dtype=np.uint64), W_, g[t], np.cumsum([b.shape[0] for b in blocks]).tolist())
        H[t] = [g[t] - int(x) for x in rk]
    return [[1] + [H[t][j] for t in range(1, K + 1)] for j in range(kr + 1)]
def divide(base, r):
    inv = [{0: 1, 1: -1, 2: 0}[i % 3] for i in range(K + 1)]; c = [1] + [0] * K
    for _ in range(r): c = [sum(c[i] * inv[s - i] for i in range(s + 1)) for s in range(K + 1)]
    return [sum(base[i] * c[s - i] for i in range(s + 1)) for s in range(K + 1)]
out = dict(n=n, member=member, seed=sd, phi=[f.tolist() for f in phi], v=v.tolist(), allowed=len(Z), slice=len(slice_), gamma=[g[t] for t in range(K + 1)])
for label, closed in (('closed', True), ('unclosed', False)):
    S_ = series(closed); rows = []
    for j in range(kr + 1):
        pred = divide(S_[0], j); rows.append(dict(random_forms=j, H=S_[j], predicted=pred, excess=[x - y for x, y in zip(S_[j], pred)]))
    out[label] = rows; print(label, [(r['random_forms'], r['excess']) for r in rows], f'({time.time()-t0:.0f}s)', flush=True)
out['closure_effect'] = [u - c for u, c in zip(out['unclosed'][0]['H'], out['closed'][0]['H'])]
print('closure effect (dim A#unclosed - dim A#closed by degree):', out['closure_effect'], flush=True)
json.dump(out, open(outp, 'w'), indent=1)
