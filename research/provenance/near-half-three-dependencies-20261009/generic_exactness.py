#!/usr/bin/env python3
"""Decide where the generic Hilbert function of two-form quotients equals the product series.

Statement checked (side notebook near-half-pc-degree, entry-2026-10-09-many-dependency-series):
g(n,m,j) = least dim (A/I)_j over m-tuples of planes of linear forms, A the exterior algebra on n
variables over the algebraic closure of F_2, I generated by the planes' two-vectors.
P(n,m,j) = coefficient of z^j in (1+z)^(n-2m) (1+2z)^m.  Inputs: lines "n m h_0..h_n" of
two_form_full_range.m2, each an example, so g(n,m,j) <= h_j (upper bound U).
Rules applied, exactly those of lem:generic-series-lower-bound:
  L(n,m,j) [g >= P] holds if 2m <= n (independent planes: g = P), or if L(n,m-1,j) holds and
  U(n-2,m-1,j-2) <= P(n-2,m-1,j-2) (for j < 2 the subtracted term is zero).
  U is a computed example, or trivially: for n < 2 there is no plane and I = 0; for m >= binom(n,2)
  generic two-vectors span the second exterior power (decomposable vectors span it), so h = 1, n, 0, ...
  Exact(n,m,j) iff L(n,m,j) and h(n,m)_j <= P(n,m,j).
Output: for each (n,m) the index (first j with P <= 0), whether every j below the index is Exact,
and the first j that is not; then totals.  Also reports whether h vanishes from the index on.
Arguments: input path, output JSON path.
"""
import json
import sys
from math import comb


def series(n, m):
    c = [comb(m, j) * 2 ** j for j in range(n + 1)]
    e = n - 2 * m
    b = [comb(e, j) if e >= 0 else (-1) ** j * comb(-e + j - 1, j) for j in range(n + 1)]
    return [sum(c[i] * b[j - i] for i in range(j + 1)) for j in range(n + 1)]


h = {}
for line in open(sys.argv[1]):
    parts = line.split()
    if len(parts) >= 3 and all(p.lstrip('-').isdigit() for p in parts):
        n, m = int(parts[0]), int(parts[1])
        if len(parts) == n + 3:
            h[(n, m)] = [int(x) for x in parts[2:]]



def upper(n, m):
    """An example's Hilbert function: computed, or one of two trivial cases."""
    if n < 2:                      # no plane: every two-vector is zero, I = 0
        return [comb(n, j) for j in range(n + 1)]
    if m >= comb(n, 2):            # generic two-vectors span the whole second exterior power
        return [1, n] + [0] * (n - 1)
    return h.get((n, m))


lower = {}


def L(n, m, j):
    key = (n, m, j)
    if key in lower:
        return lower[key]
    if 2 * m <= n:
        ok = True
    elif not L(n, m - 1, j):
        ok = False
    elif j < 2:
        ok = True
    else:
        prev = upper(n - 2, m - 1)
        ok = prev is not None and prev[j - 2] <= series(n - 2, m - 1)[j - 2]
    lower[key] = ok
    return ok


rows = []
for (n, m) in sorted(h):
    p = series(n, m)
    idx = next((j for j, v in enumerate(p) if v <= 0), n + 1)
    upper_ok = [h[(n, m)][j] <= p[j] for j in range(idx)]
    exact = [upper_ok[j] and L(n, m, j) for j in range(idx)]
    rows.append({'n': n, 'm': m, 'index': idx, 'example_equals_series_below_index': all(h[(n, m)][j] == p[j] for j in range(idx)),
                 'exact_below_index': all(exact), 'first_not_exact': next((j for j, e in enumerate(exact) if not e), None),
                 'example_zero_from_index': all(v == 0 for v in h[(n, m)][idx:]), 'h': h[(n, m)]})
json.dump(rows, open(sys.argv[2], 'w'), indent=0)
by_n = {}
for r in rows:
    t = by_n.setdefault(r['n'], [0, 0, 0, 0, []])
    t[0] += 1
    t[1] += r['example_equals_series_below_index']
    t[2] += r['exact_below_index']
    t[3] += r['example_zero_from_index']
    if not r['exact_below_index']:
        t[4].append((r['m'], r['first_not_exact']))
for n in sorted(by_n):
    t = by_n[n]
    print('n', n, 'cases', t[0], 'example equals series below index', t[1], 'generic exactness proved', t[2],
          'example zero from index', t[3], 'not proved (m, first j):', t[4][:12])
