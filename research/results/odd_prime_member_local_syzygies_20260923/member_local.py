"""Member-local generation of top syzygies on the functional top algebra G (R = n+1 rows, N = n labels, GF(3)).

Tested statement (the hypothesis a relative Taylor glue needs, degrees 2 and 3): for an inventory made of members --
selectors whose linear parts are all directions (or a random half) of a random subspace W_i of dimension d_i --
followed by uniform random selectors, the top syzygies are generated by those supported on one member plus the
Frobenius syzygies of the random forms.  Equivalently, below saturation:
  degree 2: rank span{l^2} = sum_i r2(member i) + M_rand            (random squares independent of the rest)
  degree 3: rank mu_3 = min(gamma_3, r3(members) + M_rand(gamma_1 - 1)),
where r3(members) is the degree-3 rank of the members together, and additionally r3(members) = sum_i r3(member i)
and r2(members) = sum_i r2(member i) when there are several members (members local to each other).
A shortfall below saturation is a non-local syzygy.  Ranks are those of the transposed maps on K_2, K_3 (dual bases
of G_2, G_3), each series one pass of the compiled prefix-rank kernel.
Hypothesis asserted: every linear part is nonconstant modulo constants on every row.
Usage: python3 member_local.py --n 6 --seeds 1,2 --Mrand 60 --out OUT.json"""
import argparse, itertools, json, os, sys, time
import numpy as np
from scipy import sparse
HERE = os.path.dirname(os.path.abspath(__file__)); RES = os.path.join(HERE, '..')
sys.path.insert(0, os.path.join(RES, 'odd_prime_horace_pieces_20260923'))
from horace_pieces import Board, series
from second_degree_lift import marg_basis
from freeness import predict
P = 3
def ok(f): return all(len(set(f[x])) > 1 for x in range(f.shape[0]))
def directions(d):
    out = []
    for c in itertools.product(range(3), repeat=d):
        c = np.array(c)
        if c.any() and c[np.nonzero(c)[0][0]] == 1: out.append(c)
    return out
def member(rng, R, N, d, frac):
    while True:
        A = rng.integers(0, 3, size=(d, R, N)); cs = directions(d); forms = [np.tensordot(c, A, axes=1) % 3 for c in cs]
        if all(ok(f) for f in forms): break
    if frac < 1:
        keep = sorted(rng.choice(len(forms), int(round(frac * len(forms))), replace=False)); forms = [forms[k] for k in keep]; cs = [cs[k] for k in keep]
    return forms, cs
ap = argparse.ArgumentParser(); ap.add_argument('--n', type=int, default=6); ap.add_argument('--seeds', default='1,2')
ap.add_argument('--Mrand', type=int, default=60); ap.add_argument('--out', required=True); a = ap.parse_args(); t0 = time.time()
n = a.n; R, N = n + 1, n; b = Board(R, N)
inj2, B2 = marg_basis(N, 2); assert inj2 == b.inj[2]
Kb2 = sparse.kron(sparse.identity(len(b.sets[2]), format='csr', dtype=np.int64), sparse.csr_matrix(B2 % P), format='csc')
g1, g2, g3 = R * (N - 1), Kb2.shape[1], b.Kb.shape[1]; all3 = np.arange(g3)
def blk2(f): return ((b.D(f, 1) @ (b.D(f, 2) @ Kb2)).toarray() % P).astype(np.uint8)
def blk3(f): return b.D2K(f, all3)
def ranks(forms): return [int(x) for x in series([blk2(f) for f in forms], g2)], [int(x) for x in series([blk3(f) for f in forms], g3)]
CONFIGS = [((2,), 1.0), ((3,), 1.0), ((3,), 0.5), ((4,), 1.0), ((4,), 0.5), ((5,), 1.0), ((5,), 0.5), ((3, 3), 1.0), ((4, 4), 1.0), ((2, 2, 2, 2), 1.0)]
out = dict(n=n, gamma1=g1, gamma2=g2, gamma3=g3, runs=[])
for seed in [int(s) for s in a.seeds.split(',')]:
    rng = np.random.default_rng(1000 + seed); rand = []
    while len(rand) < a.Mrand:
        f = rng.integers(0, 3, size=(R, N))
        if ok(f): rand.append(f)
    for dims, frac in CONFIGS:
        mc = [member(rng, R, N, d, frac) for d in dims]; mems = [m for m, _ in mc]
        off = np.cumsum([0] + list(dims)); fv = [[0] * int(off[i]) + [int(x) for x in c] + [0] * int(off[-1] - off[i + 1]) for i, (_, cs) in enumerate(mc) for c in cs]
        fp = list(predict(fv, int(off[-1]), g1))
        allm = [f for m in mems for f in m]; k = len(allm)
        r2, r3 = ranks(allm + rand)
        rm2, rm3 = r2[k - 1], r3[k - 1]
        if len(mems) > 1: own = [ranks(m) for m in mems]; own2 = [o[0][-1] for o in own]; own3 = [o[1][-1] for o in own]
        else: own2, own3 = [rm2], [rm3]                  # one member: its own ranks are the series prefix
        dev2 = [M for M in range(a.Mrand + 1) if r2[k - 1 + M] != min(g2, rm2 + M)]
        dev3 = [M for M in range(a.Mrand + 1) if r3[k - 1 + M] != min(g3, rm3 + M * (g1 - 1))]
        cross = next((M for M in range(a.Mrand + 1) if rm3 + M * (g1 - 1) >= g3), None)
        run = dict(seed=seed, dims=list(dims), frac=frac, member_sizes=[len(m) for m in mems], own_r2=own2, own_r3=own3,
                   members_r2=rm2, members_r3=rm3, members_additive=(rm2 == sum(own2) and rm3 == sum(own3)), freeness_prediction=fp, freeness_ok=(fp == [rm2, rm3]),
                   crossing_Mrand=cross, dev2=dev2, dev3=dev3, r2=r2[k - 1:], r3=r3[k - 1:])
        out['runs'].append(run)
        print(f'seed {seed} dims {dims} frac {frac}: sizes {run["member_sizes"]} own r2 {own2} r3 {own3}; together r2 {rm2} r3 {rm3} '
              f'(additive {run["members_additive"]}; freeness {fp} ok {run["freeness_ok"]}); crossing M_rand={cross}; deviations deg2 {dev2[:5]} ({len(dev2)}), '
              f'deg3 {dev3[:5]} ({len(dev3)}) ({time.time()-t0:.0f}s)', flush=True)
json.dump(out, open(a.out, 'w'), indent=1)
