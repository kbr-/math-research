/* Degree falls and graded Hilbert functions of random parity-clause systems over F_2.

Statement computed (side notebook near-half-pc-degree, entry-2026-10-09-regularity-measurement): rows
f_i = prod_{t<k} (l_it + c_it), i < m, with l_it random nonzero linear forms over F_2 on n variables,
independent within a row, c_it random bits.  For each degree d <= Dmax the program computes
  h[d]    = dim (A/I)_d, A = F_2[x]/(x_i^2), I generated by the top forms omega_i = prod_t l_it
            (rank of the span of x_T omega_i, |T| = d-k, in A_d);
  P[d]    = coefficient of z^d in (1+z)^(n-km) ((1+z)^k - z^k)^m, exact integer;
  bool[d] = dim B_{<=d}/K_d, B = F_2[x]/(x_i^2 - x_i), K_d = span{ x_T f_i : |T| <= d-k };
  one[d]  = whether 1 lies in K_d.
Derived: exact_through = largest D with h[d] = P[d] for all d <= D; nofall_through = largest D with
bool[d] = sum_{e<=d} h[e] for all d <= D, which by thm:colon-regular-closure (a),(c) is the statement
K_d cap B_{<=d-1} = K_{d-1} for d <= D, hence C_D = K_D and no PC refutation of degree D when one[D]
is 0.  index = first d <= Dmax with P[d] <= 0, or -1.
Validation mode, seed < 0 and k = 2: n = 2M, m = M+1, rows x_{2i} x_{2i+1} and (sum x_{2i})(sum x_{2i+1}),
all constants 0, for which prop:two-dependency-series-exactness gives h in closed form.

Arguments in groups of five: n m k seed Dmax.  n <= 32, k <= 4.  Exact arithmetic over F_2.
*/
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>

static uint64_t rng;
static unsigned rnd(void){ rng = rng*6364136223846793005ULL + 1442695040888963407ULL; return (unsigned)(rng>>33); }
static int cmp32(const void *p, const void *q){ uint32_t a = *(const uint32_t*)p, b = *(const uint32_t*)q; return a < b ? -1 : a > b; }

typedef struct { uint32_t *m; long len, cap; } poly;
static void push(poly *p, uint32_t x){ if (p->len == p->cap){ p->cap = p->cap ? 2*p->cap : 64; p->m = realloc(p->m, 4*p->cap); } p->m[p->len++] = x; }
static void normalize(poly *p){            /* sort and cancel equal pairs (coefficients mod 2) */
    qsort(p->m, p->len, 4, cmp32); long w = 0;
    for (long i = 0; i < p->len; ){ long j = i; while (j < p->len && p->m[j] == p->m[i]) j++; if ((j-i)&1) p->m[w++] = p->m[i]; i = j; }
    p->len = w;
}
/* q = p * (form + c); boolean: x^2 = x, else x^2 = 0 */
static void mul(const poly *p, uint32_t form, int c, int boolean, poly *q){
    q->len = 0;
    for (long i = 0; i < p->len; i++){
        uint32_t M = p->m[i];
        if (c) push(q, M);
        for (uint32_t f = form; f; f &= f-1){ uint32_t bit = f & -f; if (boolean || !(M & bit)) push(q, M | bit); }
    }
    normalize(q);
}
static long binom(int n, int r){ if (r < 0 || r > n) return 0; long v = 1; for (int i = 1; i <= r; i++) v = v*(n-r+i)/i; return v; }
static uint32_t gosper(uint32_t x){ uint32_t t = x | (x-1); return (t+1) | (((~t & -~t) - 1) >> (__builtin_ctz(x) + 1)); }

/* incremental rank over F_2 of vectors of N bits */
typedef struct { long N, NW, rank; uint64_t **basis; uint64_t *vec; } elim;
static void einit(elim *e, long N){ e->N = N; e->NW = (N+63)/64; e->rank = 0; e->basis = calloc(N ? N : 1, sizeof(uint64_t*)); e->vec = malloc(8*(e->NW ? e->NW : 1)); }
static void efree(elim *e){ for (long q = 0; q < e->N; q++) free(e->basis[q]); free(e->basis); free(e->vec); }
static int ereduce(elim *e, int insert){   /* returns 1 if vec reduced to zero */
    long w = e->NW - 1;
    for (;;){
        while (w >= 0 && !e->vec[w]) w--;
        if (w < 0) return 1;
        long p = (w<<6) + 63 - __builtin_clzll(e->vec[w]);
        if (!e->basis[p]){ if (insert){ e->basis[p] = malloc(8*e->NW); memcpy(e->basis[p], e->vec, 8*e->NW); e->rank++; } return 0; }
        uint64_t *b = e->basis[p]; for (long q = 0; q <= w; q++) e->vec[q] ^= b[q];
    }
}
static long lookup(const uint32_t *tab, long N, uint32_t key){ long lo = 0, hi = N-1; while (lo < hi){ long mid = (lo+hi)/2; if (tab[mid] < key) lo = mid+1; else hi = mid; } return lo; }

int main(int argc, char **argv){
    for (int g = 1; g + 4 < argc; g += 5){
        int n = atoi(argv[g]), m = atoi(argv[g+1]), k = atoi(argv[g+2]); long seed = atol(argv[g+3]); int Dmax = atoi(argv[g+4]);
        if (n > 32 || n < 2 || k < 1 || k > 4 || Dmax > 8 || m > 1024){ fprintf(stderr, "parameters out of range\n"); return 2; }
        uint32_t full = n == 32 ? 0xFFFFFFFFu : ((1u<<n) - 1);
        uint32_t (*form)[4] = malloc(sizeof(uint32_t[4])*m); int (*cst)[4] = malloc(sizeof(int[4])*m);
        if (seed < 0){
            if (k != 2 || n % 2 || m != n/2 + 1){ fprintf(stderr, "validation mode needs k = 2, n = 2M, m = M+1\n"); return 2; }
            uint32_t ev = 0, od = 0;
            for (int i = 0; i < n/2; i++){ form[i][0] = 1u<<(2*i); form[i][1] = 1u<<(2*i+1); ev |= form[i][0]; od |= form[i][1]; cst[i][0] = cst[i][1] = 0; }
            form[m-1][0] = ev; form[m-1][1] = od; cst[m-1][0] = cst[m-1][1] = 0;
        } else {
            rng = 0x9E3779B97F4A7C15ULL ^ (uint64_t)(seed*1000003L + n*131 + m*7 + k);
            for (int i = 0; i < 8; i++) rnd();
            for (int i = 0; i < m; i++){
                for (int t = 0; t < k; t++){
                    for (;;){               /* independent of the earlier forms of the row: not in their span */
                        uint32_t a = (uint32_t)(((uint64_t)rnd()<<16) ^ rnd()) & full; int ok = a != 0;
                        for (int s = 1; ok && s < (1<<t); s++){ uint32_t c = 0; for (int u = 0; u < t; u++) if ((s>>u)&1) c ^= form[i][u]; if (c == a) ok = 0; }
                        if (ok){ form[i][t] = a; break; }
                    }
                    cst[i][t] = rnd() & 1;
                }
            }
        }
        /* expand rows: top forms in A and rows in B */
        poly *top = calloc(m, sizeof(poly)), *row = calloc(m, sizeof(poly)); poly tmp = {0}, tmp2 = {0};
        for (int i = 0; i < m; i++){
            for (int boolean = 0; boolean < 2; boolean++){
                tmp.len = 0; push(&tmp, 0);
                for (int t = 0; t < k; t++){ mul(&tmp, form[i][t], boolean ? cst[i][t] : 0, boolean, &tmp2); poly sw = tmp; tmp = tmp2; tmp2 = sw; }
                poly *dst = boolean ? &row[i] : &top[i]; dst->len = 0; for (long q = 0; q < tmp.len; q++) push(dst, tmp.m[q]);
            }
        }
        long h[9], P[9], boolq[9], sumh = 0; int one[9], exact = -1, nofall = -1, index = -1, exact_ok = 1, nofall_ok = 1;
        printf("{\"n\":%d,\"m\":%d,\"k\":%d,\"seed\":%ld,\"by_degree\":[", n, m, k, seed);
        for (int d = 0; d <= Dmax; d++){
            /* product series coefficient: sum_i (-1)^i C(m,i) C(n-ki, d-ki) */
            long long pc = 0; for (int i = 0; k*i <= d; i++){ long long term = (long long)binom(m, i) * binom(n - k*i, d - k*i); pc += (i & 1) ? -term : term; }
            P[d] = (long)pc;
            /* graded rank in degree d */
            long Nd = binom(n, d); uint32_t *tab = malloc(4*(Nd ? Nd : 1));
            { long c = 0; if (d == 0) tab[c++] = 0; else { uint32_t x = (1u<<d) - 1; for (;;){ tab[c++] = x; if (c == Nd) break; x = gosper(x); } } }
            elim E; einit(&E, Nd);
            if (d >= k){
                long NT = binom(n, d-k); uint32_t T = d == k ? 0 : (1u<<(d-k)) - 1;
                for (long c = 0; c < NT; c++){
                    for (int i = 0; i < m; i++){
                        memset(E.vec, 0, 8*E.NW); int any = 0;
                        for (long q = 0; q < top[i].len; q++){ uint32_t M = top[i].m[q]; if (M & T) continue; long col = lookup(tab, Nd, M | T); E.vec[col>>6] ^= 1ULL<<(col&63); any = 1; }
                        if (any) ereduce(&E, 1);
                    }
                    if (c + 1 < NT) T = gosper(T);
                }
            }
            h[d] = Nd - E.rank; efree(&E); free(tab);
            sumh += h[d];
            /* Boolean static span at degree d */
            long N = 0; for (int e = 0; e <= d; e++) N += binom(n, e);
            uint32_t *bt = malloc(4*N); long c = 0;
            for (int e = 0; e <= d; e++){ if (e == 0){ bt[c++] = 0; continue; } long Ne = binom(n, e); uint32_t x = (1u<<e) - 1; for (long q = 0; q < Ne; q++){ bt[c++] = x; if (q + 1 < Ne) x = gosper(x); } }
            qsort(bt, N, 4, cmp32);
            elim Bq; einit(&Bq, N);
            for (int e = 0; e + k <= d; e++){
                long NT = binom(n, e); uint32_t T = e == 0 ? 0 : (1u<<e) - 1;
                for (long cc = 0; cc < NT; cc++){
                    for (int i = 0; i < m; i++){
                        memset(Bq.vec, 0, 8*Bq.NW);
                        for (long q = 0; q < row[i].len; q++){ long col = lookup(bt, N, row[i].m[q] | T); Bq.vec[col>>6] ^= 1ULL<<(col&63); }
                        ereduce(&Bq, 1);
                    }
                    if (cc + 1 < NT) T = gosper(T);
                }
            }
            boolq[d] = N - Bq.rank;
            memset(Bq.vec, 0, 8*Bq.NW); Bq.vec[0] = 1ULL; one[d] = ereduce(&Bq, 0);   /* bt[0] = 0 is the constant */
            efree(&Bq); free(bt);
            if (index < 0 && P[d] <= 0) index = d;
            if (exact_ok && h[d] == P[d]) exact = d; else exact_ok = 0;
            if (nofall_ok && boolq[d] == sumh) nofall = d; else nofall_ok = 0;
            printf("%s{\"d\":%d,\"h\":%ld,\"P\":%ld,\"bool\":%ld,\"sum_h\":%ld,\"one\":%d}", d ? "," : "", d, h[d], P[d], boolq[d], sumh, one[d]);
            fflush(stdout);
        }
        printf("],\"index\":%d,\"exact_through\":%d,\"nofall_through\":%d}\n", index, exact, nofall); fflush(stdout);
        for (int i = 0; i < m; i++){ free(top[i].m); free(row[i].m); } free(top); free(row); free(tmp.m); free(tmp2.m); free(form); free(cst);
    }
    return 0;
}
