"""dim (I1 T cap I2 T)_3 in T = F_3[V]/(cubes) for selector members I_i = (all squares of forms in W_i), W1 cap W2 = U.

Tested statement (overlap Tor): the degree-3 shortfall of member additivity, recorded in ex:member-configurations-free
as k(d1-k)(d2-k), equals dim (I1T cap I2T)_3 = Tor_1^T(T/I1T, T/I2T)_3 (I1 I2 starts in degree 4) minus the part
(I_U T)_3 generated by the selectors common to both members (squares of forms in U).
Coordinates: V = W1' + U + W2', dims d1-k, k, d2-k; W1 = W1' + U, W2 = U + W2'.  Exact ranks over F_3 (small)."""
import itertools, json, sys
import numpy as np
p = 3

def rank(M):
    M = M.copy() % p; r = 0
    for c in range(M.shape[1]):
        piv = next((i for i in range(r, M.shape[0]) if M[i, c]), None)
        if piv is None: continue
        M[[r, piv]] = M[[piv, r]]; M[r] = (M[r] * pow(int(M[r, c]), p - 2, p)) % p
        nz = [i for i in np.nonzero(M[:, c])[0] if i != r]
        M[nz] = (M[nz] - np.outer(M[nz, c], M[r])) % p; r += 1
    return r

def mons(n, deg):   # exponent vectors with entries < 3
    return [e for e in itertools.product(range(3), repeat=n) if sum(e) == deg]

def span_deg3(n, W):   # W: list of variable indices; I = (x_a x_b : a<=b in W); degree-3 part of I*T
    idx = {e: i for i, e in enumerate(mons(n, 3))}; rows = []
    for a, b in itertools.combinations_with_replacement(W, 2):
        for c in range(n):
            e = [0] * n; e[a] += 1; e[b] += 1; e[c] += 1
            if max(e) < 3:
                v = np.zeros(len(idx), dtype=np.int64); v[idx[tuple(e)]] = 1; rows.append(v)
    return np.array(rows) if rows else np.zeros((0, len(idx)), dtype=np.int64)

res = []
for d1, d2, k in [(2, 2, 1), (3, 3, 1), (3, 4, 1), (3, 3, 2), (4, 4, 2), (4, 5, 2)]:
    n = d1 + d2 - k; W1 = list(range(d1)); W2 = list(range(d1 - k, n))
    A, B = span_deg3(n, W1), span_deg3(n, W2)
    ra, rb, rab = rank(A), rank(B), rank(np.vstack([A, B]))
    shared = rank(span_deg3(n, list(range(d1 - k, d1))))   # (I_U T)_3: squares of forms in U, common to both members
    inter = ra + rb - rab
    res.append(dict(d1=d1, d2=d2, k=k, intersection=inter, shared_generators=shared, beyond_shared=inter - shared,
                    recorded_shortfall=k * (d1 - k) * (d2 - k)))
    print(json.dumps(res[-1]), flush=True)
json.dump(res, open(sys.argv[1], 'w'), indent=1)
