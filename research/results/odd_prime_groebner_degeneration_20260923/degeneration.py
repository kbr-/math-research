"""Groebner (lex) degeneration of the functional top algebra G and its initial complex.

G = F_3[x_{r,c}] / (squares, row and label collisions, row sums), R rows, N labels.  Eliminating x_{r,N-1} by the row
sum, G = F_3[y_{r,c} : c < N-1] / ((y^2) + collisions + q_rs), q_rs = sum_{c != c'} y_{r,c} y_{s,c'} for r < s: modulo
the monomial part the basis is the matchings of the R x (N-1) board.  Lex order with variables y_{r,c} (index
r*(N-1)+c) decreasing in index; in each degree t the leading monomials of the ideal generated by the q_rs are the pivots
of the echelon form of span{q_rs * m} (columns = matchings in decreasing order), computed by the compiled GF(3) rref.
Standard monomials form a simplicial complex Delta' (the initial complex); the degenerate algebra multiplies faces.
Question 1: dims of standard monomials (must equal dim G_t), and the minimal generators of the initial ideal by degree.
Question 2 (--dp): rank of the double-point map (u_j) -> sum l_j^2 u_j from (+) in(G)_1 to in(G)_3 on the degenerate
algebra, for uniform random F_3 forms in y, every prefix M (compiled prefix-rank kernel), against min(gamma_3, M(gamma_1-1)).
Usage: python3 degeneration.py --n 6 --T 3 [--dp M] --out OUT.json"""
import argparse, itertools, json, math, os, sys, time
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); RES = os.path.join(HERE, '..')
sys.path.insert(0, os.path.join(RES, 'odd_prime_alignment_mechanism_20260922')); sys.path.insert(0, os.path.join(RES, 'odd_prime_permutation_forms_20260923'))
import gf3
from gf3_prefix import prefix_ranks
def matchings(R, L, t):                       # sorted var-index tuples of t-matchings on an R x L board, lex-descending order
    if t == 0: return np.zeros((1, 0), dtype=np.int64)
    P = np.array(list(itertools.combinations(range(R), t)), dtype=np.int64); H = np.array(list(itertools.permutations(range(L), t)), dtype=np.int64)
    V = np.sort((P[:, None, :] * L + H[None, :, :]).reshape(len(P) * len(H), t), axis=1)
    V = V[np.lexsort(V.T[::-1])]               # ascending tuples = descending lex monomials
    return V
def delta(t, N): return sum((-1) ** j * math.comb(t, j) * math.perm(N, t - j) for j in range(t + 1))
ap = argparse.ArgumentParser(); ap.add_argument('--n', type=int, default=6); ap.add_argument('--T', type=int, default=3)
ap.add_argument('--dp', type=int, default=0); ap.add_argument('--all-generators', action='store_true'); ap.add_argument('--seed', type=int, default=1); ap.add_argument('--out', required=True)
a = ap.parse_args(); t0 = time.time(); n = a.n; R, N = n + 1, n; L = N - 1; v = R * L
res = dict(n=n, R=R, N=N, degrees={}, generators={}); lead = {}; std = {}
for t in range(2, a.T + 1):
    cols = matchings(R, L, t); idx = {tuple(r): k for k, r in enumerate(cols.tolist())}
    base = matchings(R, L, t - 2); rows = []
    for r, s in itertools.combinations(range(R), 2):
        free = ~np.isin(base // L, [r, s]).any(axis=1) if t > 2 else np.ones(1, dtype=bool)
        B = base[free]
        if len(B) == 0: continue
        Mq = np.zeros((len(B), len(cols)), dtype=np.uint8)
        for c, c2 in itertools.permutations(range(L), 2):
            ok = ~np.isin(B % L, [c, c2]).any(axis=1) if t > 2 else np.ones(len(B), dtype=bool)
            mons = np.sort(np.concatenate([B[ok], np.full((ok.sum(), 1), r * L + c), np.full((ok.sum(), 1), s * L + c2)], axis=1), axis=1)
            k = np.array([idx[tuple(m)] for m in mons.tolist()], dtype=np.int64); Mq[np.nonzero(ok)[0], k] = 1
        rows.append(Mq)
    M = np.vstack(rows); _, _, piv = gf3.rref(M, parallel=True); piv = set(int(p) for p in piv)
    std_t = [k for k in range(len(cols)) if k not in piv]
    lead[t] = {tuple(cols[p]) for p in piv}; std[t] = cols[std_t]
    minimal = [m for m in lead[t] if t == 2 or not any(tuple(m[:i] + m[i + 1:]) in lead[t - 1] for i in range(t))]
    exp = math.comb(R, t) * delta(t, N)
    if a.all_generators: res['generators'][t] = [[(int(x) // L, int(x) % L) for x in m] for m in sorted(minimal)]
    res['degrees'][t] = dict(matchings=len(cols), ideal=len(piv), standard=len(std_t), dim_G=exp, minimal_generators=len(minimal),
                             examples=[[(int(x) // L, int(x) % L) for x in m] for m in sorted(minimal) if all(int(x) // L < 3 for x in m)])
    print(f't={t}: matchings {len(cols)}, standard {len(std_t)} (dim G_t {exp}), minimal generators of in(I) {len(minimal)}; '
          f'e.g. {res["degrees"][t]["examples"][:3]} ({time.time()-t0:.0f}s)', flush=True)
if a.dp:
    S1 = [(x,) for x in range(v)]; S2 = [tuple(m) for m in std[2].tolist()]; S3 = [tuple(m) for m in std[3].tolist()]
    i2 = {m: k for k, m in enumerate(S2)}; i3 = {m: k for k, m in enumerate(S3)}
    pair_i = np.array([m[0] for m in S2]); pair_k = np.array([m[1] for m in S2])
    trip = np.array(S3, dtype=np.int64)                                 # face y_S3 = (face of S2) * y_v: v = one element
    rng = np.random.default_rng(700 + a.seed); forms = []
    while len(forms) < a.dp:
        f = rng.integers(0, 3, size=v)
        if all(len(set(f[r * L:(r + 1) * L].tolist() + [0])) > 1 for r in range(R)): forms.append(f)
    blocks = []
    for f in forms:
        sq = (2 * f[pair_i] * f[pair_k]) % 3                            # l^2 in the standard degree-2 basis
        B = np.zeros((v, len(S3)), dtype=np.uint8)
        for drop in range(3):                                           # y_v * y_{S3 minus v} for each face and each of its 3 vertices
            rest = [tuple(np.delete(row, drop)) for row in trip.tolist()]
            k2 = np.array([i2.get(rt, -1) for rt in rest]); ok = k2 >= 0
            vv = trip[ok, drop]; B[vv, np.nonzero(ok)[0]] = (B[vv, np.nonzero(ok)[0]] + sq[k2[ok]]) % 3
        blocks.append(B)
    P_, W = gf3.pack(np.vstack(blocks))[:2]
    ranks = prefix_ranks(np.ascontiguousarray(P_, dtype=np.uint64), W, len(S3), np.cumsum([b.shape[0] for b in blocks]).tolist())
    g1, g3 = v, len(S3); exp = [min(g3, M * (g1 - 1)) for M in range(1, a.dp + 1)]
    dev = [M for M in range(1, a.dp + 1) if ranks[M - 1] != exp[M - 1]]
    res["double_points"] = dict(gamma1=g1, gamma3=g3, ranks=[int(x) for x in ranks], expected=exp, deviations=dev)
    print(f'double points on in(G): gamma1={g1} gamma3={g3}; deviations from min(gamma3, M(gamma1-1)): {dev[:10]} ({len(dev)}) ({time.time()-t0:.0f}s)', flush=True)
json.dump(res, open(a.out, 'w'), indent=1)
