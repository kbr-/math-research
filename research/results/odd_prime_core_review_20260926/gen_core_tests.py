"""Generate the GAP input for the core route review's three tests.

Weak monomial algebra A~ = tensor_{c<N} (K + V_c), dim V_c = m, V_c^2 = 0.
Basis of A~_j: pairs (S, a) with S a j-subset of columns (sorted) and a a tuple of
flavour indices in range(m), one per column of S.

T1  Absolute irreducibility of A~_j over GF(3) under G(F_3) = GL_m(3)^N x| S_N.
    Generators: elementary generators of GL_m(3) acting on column 0, the
    transposition (0 1) and the N-cycle. Matrices act on row vectors: row i is the
    image of basis vector i. GAP's MeatAxe decides absolute irreducibility.
T2  dim l^2 l'^2 A~_1 in A~_5 for random integer forms l, l', reduced mod 3 and mod
    10007 (a proxy for characteristic 0). The statement tested: over F_3 the
    annihilator of l^2 l'^2 in A~_1 contains span(l, l'), since l^3 = 6 e_3(l);
    away from 3 it need not.
T4  Randomized-prefix clause tops of M blocks sharing the linear parts l_1..l_h (the
    constants may differ; tops see only linear parts): tau_{b,i} = l_i^2 prod_{j<=t}
    (sum_i c^b_{ji} l_i^2)^2 with independent uniform C_b in F_3^{t x h}. Statement
    tested: the tops lie in the span of the squarefree products of 2t+1 of the h
    squares (l^4 = 0), of dimension at most C(h, 2t+1), so for h = 2t+1 all M*h tops
    are proportional to P = prod_i l_i^2. These are formal products of the tops (integer
    forms reduced mod 3), not tops of clauses with constants. Reports the number of
    nonzero formal tops and the F_3 rank of all M*h of them.
T3  Number of GL_2(3)-orbits on 4-tuples of vectors of F_3^2 (column types of a
    pair of product tops at m = 2), computed in GAP.

Usage: python3 gen_core_tests.py --out tests.g  (the GAP script prints JSON lines)
"""
import argparse
import itertools
import random
from math import comb


def basis(m, N, j):
    return [(S, a) for S in itertools.combinations(range(N), j)
            for a in itertools.product(range(m), repeat=j)]


def gl_generators(m):
    gens = []
    d = [[int(r == c) for c in range(m)] for r in range(m)]
    d[0][0] = 2
    gens.append(d)
    if m >= 2:
        t = [[int(r == c) for c in range(m)] for r in range(m)]
        t[0][1] = 1
        gens.append(t)
        p = [[int(c == (r + 1) % m) for c in range(m)] for r in range(m)]
        gens.append(p)
    return gens


def act_gl(g, m, N, j):
    """Row-vector matrix of g in GL(V_0) acting on A~_j."""
    B = basis(m, N, j)
    idx = {b: i for i, b in enumerate(B)}
    M = [[0] * len(B) for _ in B]
    for i, (S, a) in enumerate(B):
        if 0 not in S:
            M[i][i] = 1
            continue
        pos = S.index(0)
        for b in range(m):
            coef = g[b][a[pos]]  # e_a -> sum_b g[b][a] e_b
            if coef % 3:
                a2 = a[:pos] + (b,) + a[pos + 1:]
                M[i][idx[(S, a2)]] = (M[i][idx[(S, a2)]] + coef) % 3
    return M


def act_perm(perm, m, N, j):
    B = basis(m, N, j)
    idx = {b: i for i, b in enumerate(B)}
    M = [[0] * len(B) for _ in B]
    for i, (S, a) in enumerate(B):
        pairs = sorted((perm[c], a[k]) for k, c in enumerate(S))
        S2 = tuple(c for c, _ in pairs)
        a2 = tuple(x for _, x in pairs)
        M[i][idx[(S2, a2)]] = 1
    return M


def mul(x, y):
    out = {}
    for (S, a), u in x.items():
        for (T, b), v in y.items():
            if set(S) & set(T):
                continue
            pairs = sorted(list(zip(S, a)) + list(zip(T, b)))
            key = (tuple(c for c, _ in pairs), tuple(f for _, f in pairs))
            out[key] = out.get(key, 0) + u * v
    return {k: v for k, v in out.items() if v}


def form(m, N, rng):
    return {((c,), (a,)): rng.randrange(-40, 41) for c in range(N) for a in range(m)}


def gap_mat(M):
    return "[" + ",".join("[" + ",".join(str(x) for x in row) + "]" for row in M) + "]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    rng = random.Random(20260926)
    lines = ["# generated by gen_core_tests.py; prints JSON lines", "one := One(GF(3));;"]
    for (m, N, j) in [(1, 5, 2), (2, 4, 2), (2, 4, 3), (2, 5, 2), (3, 3, 2)]:
        mats = [act_gl(g, m, N, j) for g in gl_generators(m)]
        mats.append(act_perm([1, 0] + list(range(2, N)), m, N, j))
        mats.append(act_perm([(c + 1) % N for c in range(N)], m, N, j))
        lines.append("gens := [" + ",".join(gap_mat(M) + "*one" for M in mats) + "];;")
        lines.append("gm := GModuleByMats(gens, GF(3));;")
        lines.append('Print("{\\"test\\": \\"T1\\", \\"m\\": %d, \\"N\\": %d, \\"j\\": %d, \\"dim\\": ", '
                     'gm.dimension, ", \\"absolutely_irreducible\\": ", MTX.IsAbsolutelyIrreducible(gm), "}\\n");'
                     % (m, N, j))
    for (m, N) in [(2, 6), (2, 7), (3, 6)]:
        B1 = basis(m, N, 1)
        B5 = basis(m, N, 5)
        idx5 = {b: i for i, b in enumerate(B5)}
        for trial in range(3):
            l, lp = form(m, N, rng), form(m, N, rng)
            tau = mul(mul(l, l), mul(lp, lp))
            rows = []
            for (S, a) in B1:
                prod = mul(tau, {(S, a): 1})
                row = [0] * len(B5)
                for k, v in prod.items():
                    row[idx5[k]] = v
                rows.append(row)
            for p in (3, 10007):
                lines.append("M := %s * One(GF(%d));;" % (gap_mat([[x % p for x in r] for r in rows]), p))
                lines.append('Print("{\\"test\\": \\"T2\\", \\"m\\": %d, \\"N\\": %d, \\"trial\\": %d, \\"p\\": %d, '
                             '\\"mN\\": %d, \\"rank\\": ", RankMat(M), "}\\n");' % (m, N, trial, p, m * N))
    for (m, N, t, h, M) in [(2, 6, 1, 3, 4), (2, 6, 1, 4, 4), (1, 10, 2, 5, 3), (1, 11, 2, 6, 3)]:
        forms = [form(m, N, rng) for _ in range(h)]
        sq = [mul(f, f) for f in forms]
        deg = 2 * (2 * t + 1)
        Bd = basis(m, N, deg)
        idxd = {b: i for i, b in enumerate(Bd)}
        rows = []
        for b in range(M):
            C = [[rng.randrange(3) for _ in range(h)] for _ in range(t)]
            q2 = []
            for j in range(t):
                q = {}
                for i in range(h):
                    for k, v in sq[i].items():
                        q[k] = q.get(k, 0) + C[j][i] * v
                q2.append(mul(q, q))
            for i in range(h):
                tau = sq[i]
                for j in range(t):
                    tau = mul(tau, q2[j])
                row = [0] * len(Bd)
                for k, v in tau.items():
                    row[idxd[k]] = v % 3
                rows.append(row)
        nonzero = sum(1 for r in rows if any(r))
        lines.append("M := %s * One(GF(3));;" % gap_mat(rows))
        lines.append('Print("{\\"test\\": \\"T4\\", \\"m\\": %d, \\"N\\": %d, \\"t\\": %d, \\"h\\": %d, '
                     '\\"blocks\\": %d, \\"tops\\": %d, \\"nonzero_tops\\": %d, \\"binom_bound\\": %d, \\"rank\\": ", RankMat(M), "}\\n");'
                     % (m, N, t, h, M, M * h, nonzero, comb(h, 2 * t + 1)))
    lines.append("V := Elements(GF(3)^2);; T := Tuples(V, 4);;")
    lines.append("orb := Orbits(GL(2,3), T, OnTuples);;")
    lines.append('Print("{\\"test\\": \\"T3\\", \\"tuples\\": ", Length(T), ", \\"orbits\\": ", Length(orb), "}\\n");')
    lines.append("QUIT;")
    with open(args.out, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
