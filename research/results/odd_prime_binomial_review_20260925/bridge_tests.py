#!/usr/bin/env python3
"""Cheap tests for the binomial route review (all tiny: 3^t <= 27 points).

1. Sunflower lead: compare the Alweiss-Lovett-Wu-Zhang threshold (C w log w)^w (C = 1, a lower
   estimate of the constant) for w = k+1, k = 2.5(K+1) ln n, with the inventory n^K.
2. Skein bridge (hybrid completion): for the three-shift pair C_000 = xyz, C_111 = (x+1)(y+1)(z+1),
   add all hybrids C_eps = prod (x_j + eps_j), eps in {0,1}^3. Report the allowed set of the pair and of
   the completion in F_3^3, and check that every fall C_eps - C_eps' telescopes into single-shift
   differences (each a product with one factor replaced by a constant).
3. Rumer bridge: the 3^t products prod (x_j + c_j), c in F_3^t, span the 2^t-dimensional multilinear
   space; check that their linear relations are generated by the one-coordinate three-term relations.
"""
import itertools, json, math, sys
import numpy as np
sys.path.insert(0, __file__.rsplit('/', 1)[0] + '/../odd_prime_one_column_cells_20260925')
from local_span import rank_mod3, points

P = 3
out = {}
# 1
rows = []
for n in (10**3, 10**6, 10**9):
    for K in (1, 2, 4):
        k = 2.5 * (K + 1) * math.log(n)
        w = k + 1
        log_threshold = w * math.log(w * math.log(w))
        rows.append({'n': n, 'K': K, 'w': round(w, 1), 'log_threshold': round(log_threshold, 1),
                     'log_inventory': round(K * math.log(n), 1)})
out['sunflower'] = {'rows': rows, 'threshold_exceeds_inventory_always': all(r['log_threshold'] > r['log_inventory'] for r in rows)}
# 2
X = points(3)
prod = lambda eps: np.prod(X + np.array(eps), axis=1) % P
pair_allowed = int(np.sum((prod((0, 0, 0)) == 0) & (prod((1, 1, 1)) == 0)))
comp = np.ones(len(X), dtype=bool)
for eps in itertools.product((0, 1), repeat=3):
    comp &= prod(eps) == 0
out['skein'] = {'pair_allowed_points': pair_allowed, 'completion_allowed_points': int(comp.sum()),
                'completion_allowed': [list(map(int, x)) for x in X[comp]]}
# single-shift differences are products: prod_{j != i}(x_j + eps_j) times a constant
ok = True
for eps in itertools.product((0, 1), repeat=3):
    for i in range(3):
        if eps[i] == 0:
            e2 = list(eps); e2[i] = 1
            d = (prod(eps) - prod(e2)) % P
            rest = np.prod([X[:, j] + eps[j] for j in range(3) if j != i], axis=0) % P
            ok &= bool(np.all(d == (-rest) % P))
out['skein']['single_shift_differences_are_products'] = ok
# 3
res = {}
for t in (2, 3):
    Y = points(t)
    prods = [np.prod(Y + np.array(c), axis=1) % P for c in itertools.product(range(3), repeat=t)]
    r, _ = rank_mod3(prods)
    # relations: vectors lam in F_3^(3^t) with sum lam_c prod_c = 0; dimension 3^t - r.
    # one-coordinate relations: (x+2) - 2(x+1) + x = 0 in coordinate i, tensored with any products elsewhere.
    idx = {c: n for n, c in enumerate(itertools.product(range(3), repeat=t))}
    rel = []
    for i in range(t):
        for other in itertools.product(range(3), repeat=t - 1):
            v = [0] * (3 ** t)
            for ci, coef in ((0, 1), (1, -2), (2, 1)):
                c = list(other); c.insert(i, ci)
                v[idx[tuple(c)]] = coef % P
            rel.append(v)
    rr, _ = rank_mod3(rel)
    ok_rel = all(not np.any(np.array(v) @ np.array(prods) % P) for v in rel)
    res[t] = {'products': 3 ** t, 'span_dim': int(r), 'relation_dim': 3 ** t - int(r),
              'one_coordinate_relation_rank': int(rr), 'relations_valid': ok_rel}
out['rumer'] = res
print(json.dumps(out), flush=True)
if '--out' in sys.argv:
    json.dump(out, open(sys.argv[sys.argv.index('--out') + 1], 'w'), indent=1)
